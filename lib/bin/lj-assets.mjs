#!/usr/bin/env node

// Generate list of imports for a directory, so the bundler can inline them as bytes.
//
//   lj-assets public > public.mjs

import { readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

var dir = process.argv[2] || 'public'
, listFiles = base => readdirSync(base).flatMap(name => {
	var file = join(base, name)
	return statSync(file).isDirectory() ? listFiles(file) : [ file ]
})
, imports = []
, entries = listFiles(dir).sort().map((file, i) => {
	var name = 'a' + i
	, url = '/' + relative(dir, file).split('\\').join('/')

	imports.push('import ' + name + " from './" + dir + url + "'")
	return "\t'" + url + "': " + name
})

process.stdout.write(
	'// Generated by lj-assets from ' + dir + '/\n\n' +
	imports.join('\n') + '\n\nexport var files = {\n' + entries.join(',\n') + '\n}\n'
)

